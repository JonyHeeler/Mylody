USER_TEMPLATE = """请根据下面的乐评时间线，生成我的「镜像音乐人生」分析。

这些时间是乐评生成时间，可近似代表我在这些时刻听过这些音乐。请你把它们当作一条音乐记忆线索：从曲目、乐评内容、情绪词、声音描述和时间顺序中，分析我的音乐品味、音乐人格、阶段变化，以及我可能在音乐里寻找的东西。

请注意：
- 只根据下面的数据分析，不要编造我的真实经历。
- 可以推测我的可能心境，但要温柔、克制、有依据。
- 输出中文正文，不要输出 JSON，不要使用表格。
- 请写得像一封私人音乐信件，而不是普通总结。
- 不要输出外层总标题，不要写「你的 2026 年夏季音乐人格年报」或类似年报标题。

乐评时间线：
{journey_payload}"""


def build_user_prompt(journey_items: list[dict]) -> str:
    """根据乐评时间线构建音乐人格用户 Prompt。

    Args:
        journey_items: 带生成时间的缓存乐评时间线

    Returns:
        str: 可发送给 AI 的用户 Prompt
    """
    payload = json.dumps(journey_items, ensure_ascii=False, indent=2)
    return USER_TEMPLATE.format(journey_payload=payload)
